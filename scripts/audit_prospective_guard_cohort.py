def bind_run(plan_path,run_root):
    raw=plan_path.read_bytes()
    plan=json.loads(raw)
    for p,d in {**plan.get('inputs',{}),**plan.get('source_hashes',{})}.items():
        if sha(Path(p).read_bytes())!=d:
            raise ValueError('bound prospective plan/source changed')
    result=json.loads((run_root/'evidence.json').read_bytes())
    if result['plan_sha256']!=sha(raw) or (run_root/'executed-plan.json').read_bytes()!=raw:
        raise ValueError('prospective plan execution differs')
    return plan,result


def additions(request,points):
    return tuple(Addition(ExactAtomRef(request.residue,n),n[0],tuple(points[n])) for n in request.missing_atoms)


def native_free_stage_check(folder,source,case,result):
    if result['ncac_status']!='evaluated':
        return dict(status=result['ncac_status'],stage_snapshots=0)
    trace_raw=(folder/'ncac-trace/evidence.json').read_bytes()
    if sha(trace_raw)!=result['trace_sha256']:
        raise ValueError('new-input NCAC trace digest differs')
    trace=json.loads(trace_raw)
    transport=json.loads((folder/'anchor-policy.json').read_bytes())
    if not trace['hooks_restored'] or not transport['research_hook_restored']:
        raise ValueError('new-input NCAC hooks not restored')
    observed={tuple(a['key']):a['xyz'] for a in read_pdb(source)}
    target=case['target']
    key=(target['chain_id'],target['sequence_number'],target['insertion_code'])
    for event in trace['events']:
        raw=(folder/'ncac-trace'/event['coordinates']).read_bytes()
        if sha(raw)!=event['coordinate_sha256']:
            raise ValueError('new-input stage snapshot changed')
        atoms=json.loads(gzip.decompress(raw))['atoms']
        current={tuple(a['key']):a['xyz'] for a in atoms}
        if len(current)!=len(atoms) or not observed.keys()<=current.keys() or any(math.dist(current[k],v)>1e-6 for k,v in observed.items()):
            raise ValueError('new-input NCAC stage moved/lost observations')
        points={k[3]:v for k,v in current.items() if k[:3]==key}
        if points!=event['target_points_angstrom']:
            raise ValueError('new-input target/full stage binding differs')
        audit_points(points,event['ca_volume_angstrom3'],case['residue_name'],event['target_cip'])
    data=transport['anchor_data']
    template=(Path(pf.__file__).parent/data['resource']).read_bytes()
    if sha(template)!=data['resource_sha256']:
        raise ValueError('new-input canonical template changed')
    resources=read_pdb(template)
    known={k[3]:v for k,v in observed.items() if k[:3]==key}
    names=[a['key'][3] for a in resources if a['key'][3] in known]
    p=[[x/10 for x in known[n]] for n in names]
    q=[[x/10 for x in a['xyz']] for a in resources if a['key'][3] in known]
    if data['names']!=names or data['reference_points_nm']!=p or data['template_points_nm']!=q:
        raise ValueError('new-input NCAC fit anchors differ')
    if len(transport['calls'])!=len(trace['overlays']):
        raise ValueError('new-input fit inventory differs')
    for used,supplied in zip(transport['calls'],trace['overlays'],strict=True):
        fit_check(used,supplied,names,p,q,'ncac')
    for step in trace['minimizer_iterations']:
        audit_points(step['target_points_angstrom'],step['ca_volume_angstrom3'])
        if step['observed_max_movement_angstrom']>1e-6:
            raise ValueError('new-input NCAC optimizer moved observations')
    parent=[e for e in trace['events'] if e['stage']=='returned-seed'][-1]['target_points_angstrom']
    proposals=json.loads((folder/'ncac-proposals.json').read_bytes())['candidates']
    if [c['relative_angle_degrees'] for c in proposals]!=[0.,120.,-120.]:
        raise ValueError('new-input NCAC parent angles changed')
    for candidate in proposals:
        check_rotation(parent,candidate['points'],candidate['relative_angle_degrees'])
    return dict(status='audited',stage_snapshots=len(trace['events']),fits=len(trace['overlays']))


def scored_view(source,request,name,points_pool,plan_root,run_root,plan,run):
    declaration=next(c for c in plan['cases'] if c['id']==name)
    saved=run['results'][name]
    records,materials,feasible=[],{},[]
    for i,points in enumerate(points_pool):
        added=additions(request,points)
        common,pdb=measure(source,request,added,anchored=False)
        filename=f'{name}/own-{i}.pdb'
        if pdb!=(plan_root/filename).read_bytes() or sha(pdb)!=plan['artifacts'][filename] or not source_records_preserved(source,pdb,declaration['generated']):
            raise ValueError('new-input candidate/source materialization differs')
        records.append(dict(index=i,common_audit=asdict(common)))
        materials[i]=(added,pdb)
        if common.accepted:
            feasible.append(i)
    if [c['index'] for c in declaration['cells']]!=feasible or [c['index'] for c in saved['cells']]!=feasible:
        raise ValueError('new-input complete feasible score pool differs')
    contexts=[]
    score_rows=[]
    for cell,expected in zip(saved['cells'],declaration['cells'],strict=True):
        if any(cell[k]!=v for k,v in expected.items()):
            raise ValueError('new-input scored declaration changed')
        contexts.append(snapshot_check(plan_root,run_root,declaration,cell))
        score_rows.append(dict(index=cell['index'],status='evaluated' if cell['score_status']=='scored' else 'execution_blocker',
            common_accepted=True,score=cell['total_score']))
    if choose_scored_own(saved['cells'])!=saved['selection']:
        raise ValueError('new-input fixed score selection differs')
    selection=choose_complete(score_rows)
    if selection['selected_index']!=saved['selection']['selected_index']:
        raise ValueError('pre-enrolled complete-pool selector disagrees with fixed scorer')
    if contexts and not all(c==contexts[0] for c in contexts):
        raise ValueError('new-input scorer context differs within pool')
    return dict(**selection,candidates=records,scored_inputs=len(score_rows)),materials,contexts


def refined_view(name,source,request,plan,run,root,guarded=False):
    case=next((c for c in plan['cases'] if c['id']==name),None)
    if case is None:
        inherited=next((c for c in plan['inherited_nonexecutions'] if c['id']==name),None)
        if inherited is None:
            raise ValueError('prospective refinement pool omitted')
        return dict(status='not_executed',reason=inherited.get('status'),selected_index=None,candidates=[]),{}
    results=run['results'][name]['cells']
    if [r['index'] for r in results]!=[c['declaration']['index'] for c in case['cells']]:
        raise ValueError('prospective refinement start inventory differs')
    guard_index=json.loads((root/'guard-evidence.json').read_bytes()) if guarded else None
    guard_traces={(t['id'],t['index']):t for t in guard_index['traces']} if guarded else {}
    candidates,score_rows,materials=[],[],{}
    for cell,result in zip(case['cells'],results,strict=True):
        i=cell['declaration']['index']
        folder=root/name/cell['declaration']['id']
        if json.loads((folder/'result.json').read_bytes())!=result:
            raise ValueError('prospective refinement retained result differs')
        if result['status']!='refined':
            candidates.append(dict(index=i,status='execution_blocker',error=result.get('error')))
            score_rows.append(dict(index=i,status='execution_blocker'))
            continue
        if (folder/'pose-snapshot.json.gz').read_bytes()!=Path(cell['snapshot']).read_bytes():
            raise ValueError('prospective refinement initial full pose not exact')
        before_raw=(folder/'before-atoms.json').read_bytes()
        after_raw=(folder/'after-atoms.json').read_bytes()
        if sha(before_raw)!=result['before_sha256'] or sha(after_raw)!=result['after_sha256']:
            raise ValueError('prospective refinement atom trace changed')
        before,after=json.loads(before_raw)['atoms'],json.loads(after_raw)['atoms']
        initial=json.loads(gzip.decompress((folder/'pose-snapshot.json.gz').read_bytes()))
        if {tuple(a['key']):a['xyz'] for a in before}!=snapshot_atoms(initial):
            raise ValueError('prospective refinement before trace not bound to score pose')
        motion=mobility_check(before,after,case['case'],plan['protected_numerical_bound_angstrom'])
        if not result['original_pose_exact'] or not result['graph_unchanged'] or result['convergence_claim'] or result['coordinate_restore_performed']:
            raise ValueError('prospective refinement scope claim differs')
        if set(result['score_terms'])!=set(cell['saved']['score_terms']) or any(t['weight']!=cell['saved']['score_terms'][k]['weight'] for k,t in result['score_terms'].items()):
            raise ValueError('prospective refinement score weights changed')
        if not math.isclose(sum(t['raw']*t['weight'] for t in result['score_terms'].values()),result['final_raw_score'],rel_tol=1e-10,abs_tol=1e-8):
            raise ValueError('prospective refinement final score terms differ')
        guard_decision=None
        cycle_audits=[]
        if guarded:
            trace=guard_traces[(name,i)]
            policy=plan['guard_protocol']
            baseline=Path(policy['parent_run'])/name/cell['declaration']['id']
            for cycle,descriptor in enumerate(trace['phases'],1):
                phase_raw=(folder/f'cycle-{cycle}.json').read_bytes()
                phase=json.loads(phase_raw)
                if sha(phase_raw)!=descriptor['phase_sha256'] or phase['cycle']!=cycle:
                    raise ValueError('prospective guard phase inventory differs')
                atoms=phase['atoms']
                if cycle==1 and (atoms!=json.loads((baseline/'after-atoms.json').read_bytes())['atoms'] or phase['raw_score']!=json.loads((baseline/'result.json').read_bytes())['final_raw_score']):
                    raise ValueError('prospective first guard cycle not exact C')
                phase_motion=mobility_check(before,atoms,case['case'],plan['protected_numerical_bound_angstrom'])
                gradient=phase['gradient']
                maximum=max(abs(c['analytic_per_degree']) for c in gradient['components'])
                expected_dimensions=1 if request.residue_name=='VAL' else 2
                if sorted(c['chi'] for c in gradient['components'])!=list(range(1,expected_dimensions+1)) or maximum!=gradient['maximum_per_degree'] or not gradient['original_pose_unchanged']:
                    raise ValueError('prospective guard actual gradient inventory differs')
                if max(gradient['mapped_motion'].values())>policy['mapped_endpoint_numerical_bound_angstrom'] or abs(gradient['raw_score']-phase['raw_score'])>policy['center_score_absolute_bound'] or abs(gradient['minimizer_center_score']-gradient['raw_score'])>policy['center_score_absolute_bound']:
                    raise ValueError('prospective guard derivative objective/mapped motion differs')
                guard_decision=expected_decision(maximum,cycle,policy['total_cycle_limit'],policy['cutoff_per_degree'])
                if guard_decision!=phase['decision'] or descriptor['decision']!=guard_decision or (cycle<len(trace['phases']) and guard_decision!='continue'):
                    raise ValueError('prospective guard continuation policy differs')
                points={a['key'][-1]:a['xyz'] for a in atoms if a['key'][:4]==case['case']['target_key'] and not a['is_hydrogen'] and not a['is_virtual']}
                phase_common,_=measure(source,request,additions(request,points),anchored=False)
                cycle_audits.append(dict(cycle=cycle,decision=guard_decision,gradient_maximum_per_degree=maximum,
                    movement=phase_motion,common_audit=asdict(phase_common)))
            if not cycle_audits or len(cycle_audits)>policy['total_cycle_limit'] or guard_decision=='continue' or trace['final_decision']!=guard_decision or phase['atoms']!=after or phase['raw_score']!=result['final_raw_score']:
                raise ValueError('prospective guard final phase/result differs')
        points={a['key'][-1]:a['xyz'] for a in after if a['key'][:4]==case['case']['target_key'] and not a['is_hydrogen'] and not a['is_virtual']}
        added=additions(request,points)
        common,pdb=measure(source,request,added,anchored=False)
        materials[i]=(added,pdb)
        candidates.append(dict(index=i,status='evaluated',common_audit=asdict(common),movement=motion,
            raw_score=result['final_raw_score'],guard_decision=guard_decision,cycles=cycle_audits))
        score_rows.append(dict(index=i,status='evaluated',common_accepted=common.accepted,
            score=result['final_raw_score'],guard_decision=guard_decision))
    return dict(**choose_complete(score_rows,guarded=guarded),candidates=candidates),materials


def freeze_manifest(paths,output):
    inputs={}
    for name,value in paths.items():
        path=Path(value)
        if name.endswith('_plan'):
            inputs[str(path)]=sha(path.read_bytes())
        else:
            for file in sorted(path.rglob('*')):
                if file.is_file() and not file.name.endswith(('-reference.pdb','-original.pdb')):
                    inputs[str(file)]=sha(file.read_bytes())
    write(output,dict(schema='dvbfixer.prospective-guard-audit-manifest.v1',paths=paths,inputs=inputs,
        audit_script_sha256=sha(Path(__file__).read_bytes()),native_coordinates_read=False,
        policy='pre-download scientific kernels and choose_complete unchanged; this manifest binds completed runs before native report'))


def select(manifest_path,output,emit=True):
    manifest=json.loads(manifest_path.read_bytes())
    if manifest['audit_script_sha256']!=sha(Path(__file__).read_bytes()):
        raise ValueError('prospective all-arm auditor changed after freeze')
    for p,d in manifest['inputs'].items():
        if sha(Path(p).read_bytes())!=d:
            raise ValueError('completed prospective run artifact changed')
    p={k:Path(v) for k,v in manifest['paths'].items()}
    masks=json.loads((p['masks']/'plan.json').read_bytes())
    verify(masks['enrollment'])
    _,prepared=bind_run(p['masks']/'plan.json',p['preparation'])
    prep_scores,scored=bind_run(p['preparation']/'score-plan/plan.json',p['preparation_score'])
    mean_protocol=json.loads(p['mean_plan'].read_bytes())
    mean_plan,mean_scores=bind_run(p['means']/'score-plan/plan.json',p['mean_score'])
    cplan,crun=bind_run(p['c_plan'],p['c_run'])
    gplan,grun=bind_run(p['guard_plan'],p['guard_run'])
    settings=json.loads((p['c_run']/'stopping-control-settings.json').read_bytes())
    if not settings['hook_restored'] or any(s!=cplan['minimizer'] for s in settings['actual_minimizers']):
        raise ValueError('prospective C runtime settings differ')
    guarded=json.loads((p['guard_run']/'guard-evidence.json').read_bytes())
    if not guarded['hook_restored'] or guarded['plan_sha256']!=sha(p['guard_plan'].read_bytes()):
        raise ValueError('prospective guard runtime binding differs')
    geometry=json.loads((p['means']/'geometry-before-scoring.json').read_bytes())
    means={c['id']:c for c in mean_protocol['cases']}
    reports,replay={},{}
    for case in masks['cases']:
        name=case['id']
        row=prepared['results'][name]
        folder=p['preparation']/name
        source=(p['masks']/case['source']).read_bytes()
        if source!=(folder/'input.pdb').read_bytes() or sha(source)!=masks['artifacts'][case['source']]:
            raise ValueError('prospective masked source changed')
        if row['status']=='shared_admission_refused':
            try:
                plan_branched_source(source,ComponentInstanceRef(**case['target']))
            except ValueError as error:
                if str(error)!=row['reason']:
                    raise ValueError('prospective shared refusal differs') from error
            else:
                raise ValueError('prospective shared refusal no longer reproduced')
            reports[name]=dict(status=row['status'],reason=row['reason'],arms={})
            continue
        request=plan_branched_source(source,ComponentInstanceRef(**case['target'])).request
        stages=native_free_stage_check(folder,source,case,row)
        arm_records,materials={},{}
        own=json.loads((folder/'own-attempts.json').read_bytes())
        own_points=[{a['atom']['name']:a['xyz'] for a in attempt['candidate']['additions']} for attempt in own['attempts']]
        arm_records['own'],materials['own'],own_context=scored_view(source,request,name+'-baseline',own_points,p['preparation']/'score-plan',p['preparation_score'],prep_scores,scored)
        auxiliary=None
        if row['ncac_status']=='evaluated':
            ncac_points=[c['points'] for c in json.loads((folder/'ncac-proposals.json').read_bytes())['candidates']]
            auxiliary,_,ncac_context=scored_view(source,request,name+'-ncac',ncac_points,p['preparation']/'score-plan',p['preparation_score'],prep_scores,scored)
            if own_context and ncac_context and own_context[0]!=ncac_context[0]:
                raise ValueError('prospective baseline/NCAC control context differs')
        if row['stock']['status']=='evaluated':
            stock=json.loads((folder/'stock-proposal.json').read_bytes())
            added=tuple(Addition(ExactAtomRef(request.residue,a['atom']['name']),a['element'],tuple(a['xyz'])) for a in stock['additions'])
            common,pdb=measure(source,request,added,anchored=False)
            if canonical(asdict(common))!=row['stock']['common_audit'] or pdb!=(folder/'stock-proposal.pdb').read_bytes():
                raise ValueError('prospective stock common output differs')
            arm_records['stock']=dict(status='selected' if common.accepted else 'empty_geometry_pool',selected_index=0 if common.accepted else None,common_audit=asdict(common))
            materials['stock']={0:(added,pdb)}
        else:
            arm_records['stock']=dict(row['stock'],selected_index=None)
            materials['stock']={}
        if means[name]['status']=='generation_ready':
            declaration=means[name]
            points=[]
            for sample in declaration['samples']:
                delta=(sample['mean_degrees']-declaration['parent_chi_degrees']+180)%360-180
                points.append(rotate_distal(declaration['parent_points'],delta))
            fixed,material,contexts=scored_view(source,request,name+'-means',points,p['means']/'score-plan',p['mean_score'],mean_plan,mean_scores)
            if own_context and contexts and own_context[0]!=contexts[0]:
                raise ValueError('prospective cross-arm fixed-score context differs')
            arm_records['mean_fixed'],materials['mean_fixed']=fixed,material
            valid=[c for c in fixed['candidates'] if c['common_audit']['accepted']]
            weights={i:s['probability'] for i,s in enumerate(declaration['samples'])}
            prior=max(valid,key=lambda c:(weights[c['index']],-c['index']))['index'] if valid else None
            if prior!=geometry['results'][name]['prior_selected_index']:
                raise ValueError('prospective raw-family-weight selector differs')
            arm_records['mean_prior']=dict(status='selected' if prior is not None else 'empty_geometry_pool',selected_index=prior)
            materials['mean_prior']=material
            arm_records['mean_c'],materials['mean_c']=refined_view(name,source,request,cplan,crun,p['c_run'])
            arm_records['mean_guard'],materials['mean_guard']=refined_view(name,source,request,gplan,grun,p['guard_run'],guarded=True)
        else:
            for arm in ('mean_prior','mean_fixed','mean_c','mean_guard'):
                arm_records[arm]=dict(status='not_executed',reason=means[name].get('reason') or means[name]['status'],selected_index=None)
                materials[arm]={}
        reports[name]=dict(status='audited',stages=stages,arms=arm_records,auxiliary_ncac_relative_control=auxiliary)
        replay[name]=(request,source,materials)
    ledger=dict(schema='dvbfixer.prospective-guard-selection.v1',cases=reports,systems=masks['systems'],
        arm_order=ARMS,manifest_sha256=sha(manifest_path.read_bytes()),audit_script_sha256=sha(Path(__file__).read_bytes()),
        native_coordinates_read=False,profile_selected=False,production_changed=False)
    if emit:
        write(output,ledger)
    elif canonical(ledger)!=json.loads(output.read_bytes()):
        raise ValueError('prospective selections changed before native report')
    return ledger,replay,masks,p


def report(manifest_path,ledger_path,output):
    ledger,replay,masks,paths=select(manifest_path,ledger_path,emit=False)
    by_name={c['id']:c for c in masks['cases']}
    results={}
    for name,(request,source,methods) in replay.items():
        original=by_name[name]
        native=(paths['masks']/original['reference']).read_bytes()
        if sha(native)!=masks['artifacts'][original['reference']]:
            raise ValueError('prospective native reporting source differs')
        truth={a.name:a.position for a in _parse_atom_lines(native.decode().splitlines(keepends=True)) if _component_ref(a)==request.residue}
        native_common,_=measure(source,request,additions(request,truth),anchored=False)
        accuracies={}
        for arm in ARMS:
            selected=ledger['cases'][name]['arms'][arm]['selected_index']
            if selected is not None:
                accuracies[arm]=accuracy(request,*methods[arm][selected],truth)
        results[name]=dict(accuracies=accuracies,native_common_audit=asdict(native_common))
    aggregate={}
    for arm in ARMS:
        values=[r['accuracies'][arm]['rounded']['exact_name_rmsd_angstrom'] for r in results.values() if arm in r['accuracies']]
        sym=[r['accuracies'][arm]['rounded']['generated_only_val_symmetry_rmsd_angstrom'] for r in results.values() if arm in r['accuracies']]
        aggregate[arm]=dict(planned=len(masks['cases']),selected=len(values),
            exact_median_angstrom=statistics.median(values) if values else None,
            generated_val_symmetry_median_angstrom=statistics.median(sym) if sym else None)
    paired=[name for name,r in results.items() if all(a in r['accuracies'] for a in ARMS)]
    write(output,dict(schema='dvbfixer.prospective-guard-report.v1',cases=results,aggregate=aggregate,
        complete_all_arm_mask_ids=paired,selection_ledger_sha256=sha(ledger_path.read_bytes()),
        manifest_sha256=sha(manifest_path.read_bytes()),native_reporting_after_all_choices=True,
        scientific_qualification=False,profile_selected=False,production_changed=False,table_data_included=False))
    print(json.dumps(dict(aggregate=aggregate,complete_all_arm_masks=len(paired)),indent=2))


