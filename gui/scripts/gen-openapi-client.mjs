import crypto from 'node:crypto'
import fs from 'node:fs'
import os from 'node:os'
import path from 'node:path'
import { pathToFileURL } from 'node:url'
import { build } from 'esbuild'
import openapiTS, { astToString } from 'openapi-typescript'

const root = path.resolve(import.meta.dirname, '..')
const openapiFile = path.join(root, 'openapi.json')
const clientFile = path.join(root, 'src', 'generated', 'dvbfixer-api.ts')
const check = process.argv.includes('--check')
const temporary = path.join(os.tmpdir(), `dvbfixer-openapi-${crypto.randomUUID()}.mjs`)

await build({
  entryPoints: [path.join(root, 'server', 'naming-api-schema.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  outfile: temporary,
})

try {
  const module = await import(`${pathToFileURL(temporary).href}?v=${crypto.randomUUID()}`)
  const document = module.NAMING_OPENAPI_DOCUMENT
  const openapi = `${JSON.stringify(document, null, 2)}\n`
  const nodes = await openapiTS(document)
  const client = `// Generated by scripts/gen-openapi-client.mjs. Do not edit.\n${astToString(nodes)}`
  const outputs = [[openapiFile, openapi], [clientFile, client]]
  const drift = outputs.filter(([file, content]) => {
    try { return fs.readFileSync(file, 'utf8') !== content } catch { return true }
  })
  if (check) {
    if (drift.length) {
      console.error(`OpenAPI client drift: ${drift.map(([file]) => path.relative(root, file)).join(', ')}`)
      process.exitCode = 1
    } else {
      console.log('OpenAPI document and generated client are in sync.')
    }
  } else {
    for (const [file, content] of drift) {
      fs.mkdirSync(path.dirname(file), { recursive: true })
      fs.writeFileSync(file, content)
      console.log(`wrote ${path.relative(root, file)}`)
    }
  }
} finally {
  fs.rmSync(temporary, { force: true })
}
