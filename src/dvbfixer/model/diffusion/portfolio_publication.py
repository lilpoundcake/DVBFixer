"""Audited manifest-last private portfolio bundles and exact-key read-only resume.

No schema-4 sampling identity, public profile, or single-seed provenance is
invented. A directory is ready only after its committed bundle.json is audited.
"""
from __future__ import annotations

import hashlib
import os
import tempfile
from dataclasses import asdict, dataclass
from pathlib import Path

from dvbfixer.ffutils.dat import DatRecord
from dvbfixer.model.diffusion.bundle_commit import commit_manifest_last
from dvbfixer.model.diffusion.contract import (
    ArtifactReference,
    DiffusionContractError,
    DiffusionRequest,
)
from dvbfixer.model.diffusion.portfolio_contract import PortfolioBundleIndex, PortfolioEvidence
from dvbfixer.model.diffusion.portfolio_evidence import (
    PortfolioEvidenceAudit,
    audit_portfolio_evidence,
    json_bytes,
    portfolio_resume_key,
    strict_json,
)
from dvbfixer.model.diffusion.private_artifact import (
    read_private_artifact_bytes,
    read_private_file_bytes,
)
from dvbfixer.model.diffusion.scope import _parse_coordinate_records

_NAMES = {
    "request": "request.json", "source": "source.pdb", "selected": "selected.pdb", "candidate": "candidate.pdb",
    "search_protocol": "search-protocol.json", "search_report": "search-report.json",
    "selection_source": "selection-source.py", "repair_report": "repair-report.json",
    "repair_selector_source": "repair-selector-source.py", "repair_kernel_source": "repair-kernel-source.py",
    "repair_conditioning_source": "repair-conditioning-source.py",
    "input-original": "input-original.pdb", "input-prepared": "input-prepared.pdb",
    "input-repair-report": "input-repair-report.json", "input-repair-request": "input-repair-request.json",
}


def portfolio_dat_record(request: DiffusionRequest, candidate: bytes) -> DatRecord:
    """Record exactly diffusion-owned atoms; source completions remain conditioning."""
    records, _, _ = _parse_coordinate_records(candidate.decode("utf-8").splitlines())
    by_atom = {r.identity: r for r in records}
    result = DatRecord(description="Experimental multi-parent gap portfolio; exact generated-only ownership; not qualified")
    for atom in request.generated_atoms:
        record = by_atom.get(atom)
        if record is None:
            raise DiffusionContractError("portfolio .dat is missing a declared generated atom")
        result.added_atoms.append({"chain": atom.chain, "resid": atom.residue_number, "icode": atom.insertion_code,
            "resname": record.residue_name, "atom": atom.atom_name, "element": record.element})
        key = f"{atom.chain}/{record.residue_name}{atom.residue_number}{atom.insertion_code}"
        result.residue_summary.setdefault(key, {"heavy": 0, "hydrogen": 0})[
            "hydrogen" if record.element in {"H", "D"} else "heavy"] += 1
    return result


def _filename(role):
    if role in _NAMES:
        return _NAMES[role]
    # Parent roles are generated by the typed contract, never supplied as paths.
    suffix = ".pdb" if role.endswith(("coordinates", "raw")) else ".json"
    return role + suffix


def _snapshot(evidence):
    value = evidence.to_dict()
    for role, artifact in evidence.artifacts().items():
        reference = asdict(ArtifactReference(_filename(role), artifact.sha256))
        if role.startswith("parent-"):
            _, index, name = role.split("-", 2)
            value["parents"][int(index)][name] = reference
        elif role in {"input-original", "input-prepared", "input-repair-report", "input-repair-request"}:
            name = {"input-original": "original", "input-prepared": "prepared",
                    "input-repair-report": "report", "input-repair-request": "request_snapshot"}[role]
            value["preparation"][name] = reference
        else:
            value[role] = reference
    return PortfolioEvidence.from_dict(value)


def _durable_write(path, data):
    with path.open("xb") as stream:
        stream.write(data)
        stream.flush()
        os.fsync(stream.fileno())


def publish_portfolio_bundle(evidence: PortfolioEvidence, workspace: Path, destination: Path) -> Path:
    """Audit before reservation; retain failed staging, never adopt an orphan root."""
    if destination.name in {"", ".", ".."} or destination.parent.is_symlink():
        raise ValueError("portfolio destination needs an explicit name and regular parent")
    destination = destination.parent.resolve(strict=True) / destination.name
    if destination.exists() or destination.is_symlink():
        raise FileExistsError(destination)
    audit = audit_portfolio_evidence(evidence, workspace)
    snapshot = _snapshot(evidence)
    payloads = {_filename(role): data for role, data in audit.payloads.items()}
    payloads["portfolio-evidence.json"] = snapshot.to_json().encode("utf-8")
    payloads["candidate.dat"] = json_bytes(portfolio_dat_record(audit.request, audit.payloads["candidate"]).to_dict())
    payloads["validation.json"] = json_bytes(audit.validation_record())

    def reference(name):
        return ArtifactReference(name, hashlib.sha256(payloads[name]).hexdigest())

    index = PortfolioBundleIndex(1, reference("portfolio-evidence.json"), reference("candidate.dat"),
        reference("validation.json"), portfolio_resume_key(snapshot))
    staging = Path(tempfile.mkdtemp(prefix=".portfolio-staging-", dir=destination.parent))
    for name, data in payloads.items():
        _durable_write(staging / name, data)
    _durable_write(staging / "bundle.json", index.to_json().encode("utf-8"))
    read_portfolio_bundle(staging)
    commit_manifest_last(staging, destination)
    descriptor = os.open(destination.parent, os.O_RDONLY | os.O_DIRECTORY)
    try:
        os.fsync(descriptor)
    finally:
        os.close(descriptor)
    return destination


@dataclass(frozen=True)
class PublishedPortfolio:
    directory: Path
    index: PortfolioBundleIndex
    evidence: PortfolioEvidence
    audit: PortfolioEvidenceAudit
    dat: DatRecord

    @property
    def candidate_bytes(self):
        return self.audit.payloads["candidate"]


def read_portfolio_bundle(directory: Path) -> PublishedPortfolio:
    """Recompute custody, source preparation, geometry, mobility and exact .dat."""
    if directory.is_symlink() or not directory.is_dir():
        raise ValueError("portfolio bundle must be a regular directory")
    root = directory.resolve(strict=True)
    index = PortfolioBundleIndex.from_dict(strict_json(read_private_file_bytes(root, "bundle.json", max_bytes=64_000)))
    evidence = PortfolioEvidence.from_dict(strict_json(read_private_artifact_bytes(root, index.evidence, max_bytes=128_000)))
    paths = [a.path for a in evidence.artifacts().values()] + [index.evidence.path, index.dat.path, index.validation.path, "bundle.json"]
    if (len(set(paths)) != len(paths) or any(Path(path).name != path for path in paths)
            or {p.name for p in root.iterdir()} != set(paths)):
        raise DiffusionContractError("portfolio bundle must contain exactly its distinct flat artifacts")
    if portfolio_resume_key(evidence) != index.resume_key:
        raise DiffusionContractError("portfolio resume identity differs from manifest")
    audit = audit_portfolio_evidence(evidence, root)
    dat_bytes = read_private_artifact_bytes(root, index.dat, max_bytes=4_000_000)
    dat = DatRecord.from_json(dat_bytes.decode("utf-8"))
    expected = portfolio_dat_record(audit.request, audit.payloads["candidate"])
    if dat.to_dict() != expected.to_dict() or dat_bytes != json_bytes(expected.to_dict()):
        raise DiffusionContractError("portfolio .dat differs from exact generated-only ownership")
    validation = read_private_artifact_bytes(root, index.validation, max_bytes=4_000_000)
    if validation != json_bytes(audit.validation_record()):
        raise DiffusionContractError("portfolio validation receipt differs from independent audit")
    return PublishedPortfolio(root, index, evidence, audit, dat)


def resume_portfolio_bundle(directory: Path, expected: PortfolioEvidence) -> PublishedPortfolio:
    """Read-only exact reuse, never repair/resample or adopt an incomplete directory."""
    published = read_portfolio_bundle(directory)
    if published.index.resume_key != portfolio_resume_key(expected):
        raise DiffusionContractError("portfolio resume input/parents/choices/operation/software differ")
    return published
